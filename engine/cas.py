"""Проверка регистрационного номера CAS по контрольной цифре.

Зачем это в safety-critical системе. CAS — ключ идентичности вещества: по нему
подтягиваются физхимия (PubChem), транспортный класс, GHS. Опечатка в номере — это либо
пустое обогащение (лучший случай), либо данные ЧУЖОГО вещества на карточке (худший).

Что делает модуль: считает контрольную цифру и говорит «номер корректен / некорректен».
Чего он НЕ делает и делать не будет: **не исправляет** номер. Подобрать «похожий верный»
CAS — это выдумать нормативку, а сверка с первоисточником остаётся за человеком. Модуль
только поднимает флаг.

Алгоритм (ГОСТ-нейтральный, определён CAS Registry): для номера N-M-C цифры части N+M
читаются справа налево, умножаются на 1, 2, 3, … и сумма по модулю 10 равна C.

Чистый stdlib — работает без numpy и без установленного стека сервиса.
"""

__all__ = ["is_valid", "check", "audit"]

СТАТУС_ОК = "valid"
СТАТУС_ПУСТО = "absent"
СТАТУС_ФОРМА = "malformed"
СТАТУС_СУММА = "invalid_checksum"

_ПОЯСНЕНИЕ = {
    СТАТУС_ОК: None,
    СТАТУС_ПУСТО: "CAS не указан",
    СТАТУС_ФОРМА: "CAS записан не в формате NNNNNNN-NN-N",
    СТАТУС_СУММА: ("CAS не проходит контрольную цифру — вероятна опечатка в источнике. "
                   "Номер не исправляется автоматически: сверьте с первоисточником."),
}


def is_valid(cas) -> bool:
    """True только для синтаксически корректного номера с верной контрольной цифрой."""
    return check(cas)["status"] == СТАТУС_ОК


def check(cas) -> dict:
    """Разбор одного номера. Возвращает {cas, status, ok, note}."""
    сырое = "" if cas is None else str(cas).strip()
    if not сырое:
        return _итог(сырое, СТАТУС_ПУСТО)

    части = сырое.split("-")
    if len(части) != 3 or not all(ч.isdigit() for ч in части):
        return _итог(сырое, СТАТУС_ФОРМА)

    основа, середина, контрольная = части
    # Формат CAS: 2–7 цифр, дефис, 2 цифры, дефис, 1 цифра.
    if not (2 <= len(основа) <= 7 and len(середина) == 2 and len(контрольная) == 1):
        return _итог(сырое, СТАТУС_ФОРМА)

    цифры = (основа + середина)[::-1]
    сумма = sum(int(ц) * (позиция + 1) for позиция, ц in enumerate(цифры))
    статус = СТАТУС_ОК if сумма % 10 == int(контрольная) else СТАТУС_СУММА
    return _итог(сырое, статус)


def audit(records, cas_key="cas", name_key="name") -> dict:
    """Аудит списка веществ. Возвращает сводку + поимённый список подозрительных номеров.

    Ничего не чинит и не выбрасывает — только считает и называет."""
    сводка = {СТАТУС_ОК: 0, СТАТУС_ПУСТО: 0, СТАТУС_ФОРМА: 0, СТАТУС_СУММА: 0}
    подозрительные = []
    for запись in records or []:
        итог = check(запись.get(cas_key))
        сводка[итог["status"]] += 1
        if итог["status"] in (СТАТУС_ФОРМА, СТАТУС_СУММА):
            подозрительные.append({
                "name": запись.get(name_key),
                "cas": итог["cas"],
                "status": итог["status"],
                "confidence": запись.get("confidence"),
            })
    return {
        "checked": sum(сводка.values()),
        "by_status": сводка,
        "suspect": sorted(подозрительные, key=lambda з: (з["status"], з["name"] or "")),
        "note": ("Контрольная цифра CAS проверяется на лету. Номера с ошибкой НЕ исправляются "
                 "автоматически — исправление подбором было бы выдумыванием идентификатора. "
                 "Обогащение по такому номеру не подтягивается (fail-closed), карточка помечается."),
    }


def _итог(сырое, статус):
    return {"cas": сырое, "status": статус, "ok": статус == СТАТУС_ОК, "note": _ПОЯСНЕНИЕ[статус]}


if __name__ == "__main__":  # самотест без сети и без данных
    примеры = [("7664-93-9", True), ("7782-50-5", True), ("1319-77-3", True),
               ("1319-77-2", False), ("24-25-79-8", False), ("", False), (None, False)]
    for значение, ожидание in примеры:
        факт = is_valid(значение)
        отметка = "ok " if факт == ожидание else "FAIL"
        print(f"{отметка} {значение!r:>14} → {check(значение)['status']}")
