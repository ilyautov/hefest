# -*- coding: utf-8 -*-
"""
Расшифровка особых отметок СанПиН 1.2.3685-21 (раздел гигиенических нормативов воздуха рабочей зоны).
Эти отметки УЖЕ есть в нашей базе (поле `special` + `skin_hazard`) из ингеста ГН/СанПиН — но в UI не
расшифрованы. А они безопасно-критичны: меняют режим контроля и СИЗ. Здесь только расшифровка
официальных обозначений, без выдумывания значений.

Обозначения (СанПиН 1.2.3685-21):
  О — вещество с остронаправленным механизмом действия; требует автоматического контроля
      содержания в воздухе (нельзя ограничиваться периодическими замерами).
  А — вещество, способное вызывать аллергические заболевания.
  К — канцероген (вещество, опасное для человека по канцерогенному действию).
  Ф — аэрозоль преимущественно фиброгенного действия (АПФД) — пыль, поражающая лёгкие.
  + — требуется специальная защита кожи и глаз (в нашей базе хранится отдельным полем skin_hazard).
"""

_FLAGS = {
    "О": {"code": "О", "label": "остронаправленного действия",
          "meaning": "Требуется непрерывный (автоматический) контроль содержания в воздухе — "
                     "периодических замеров недостаточно.", "severity": "high"},
    "К": {"code": "К", "label": "канцероген",
          "meaning": "Опасен по канцерогенному действию. Особый режим: минимизация контакта, "
                     "учёт, медосмотры.", "severity": "high"},
    "А": {"code": "А", "label": "аллерген",
          "meaning": "Способен вызывать аллергические заболевания. Защита кожи и дыхания, "
                     "контроль сенсибилизации.", "severity": "medium"},
    "Ф": {"code": "Ф", "label": "фиброгенная пыль (АПФД)",
          "meaning": "Аэрозоль преимущественно фиброгенного действия — поражает лёгкие. "
                     "Противоаэрозольные СИЗ, контроль пыли.", "severity": "medium"},
}
_SKIN = {"code": "+", "label": "опасно при попадании на кожу",
         "meaning": "Требуется специальная защита кожи и глаз (вещество проникает/действует через кожу).",
         "severity": "high"}

import re
# Поле special — код ТОЛЬКО если вся строка из символов-кодов (О/К/А/Ф, цифры, запятые, пробелы).
# У части веществ это поле перезаписано свободным текстом (аварийная заметка) — такие НЕ декодируем,
# иначе буквы из слов («Окислитель») ложно дадут «канцероген». Цена ошибки = здоровье.
_CODE_ONLY = re.compile(r"^[ОКАФOAK0-9,\.\s]+$")


def _is_code(special):
    s = (special or "").strip()
    return bool(s) and bool(_CODE_ONLY.fullmatch(s))


def decode(special, skin_hazard=None):
    """special ('О, К, А') + skin_hazard -> расшифровка отметок СанПиН. Свободный текст игнорируется."""
    out, seen = [], set()
    if _is_code(special):
        raw = special.upper().replace("O", "О").replace("A", "А").replace("K", "К")
        for ch in raw:
            f = _FLAGS.get(ch)
            if f and f["code"] not in seen:
                seen.add(f["code"]); out.append(f)
    if skin_hazard:
        out.append(_SKIN)
    return out


def summary(sub):
    """Полная справка по веществу из данных СанПиН: ПДК, класс, агрегатное состояние, отметки."""
    flags = decode(sub.get("special"), sub.get("skin_hazard"))
    return {
        "pdk_mgm3": sub.get("pdk_mgm3"),
        "hazard_class": sub.get("hazard_class"),
        "flags": flags,
        "source": "СанПиН 1.2.3685-21 (гигиенические нормативы воздуха рабочей зоны)",
        "needs_review": True,
        "note": "Особые отметки и ПДК — из ГН/СанПиН. Сверяйте с действующей редакцией "
                "(СанПиН 1.2.3685-21 действует до 01.03.2027).",
    } if (flags or sub.get("pdk_mgm3")) else None
