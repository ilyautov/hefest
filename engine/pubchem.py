# Группировка H-кодов для краткого вывода
def h_label(code):
    return H_RU.get(code)


def decode_hcodes(codes):
    """Список H-кодов -> [{code, text}] (текст по ГОСТ 31340, либо None если код вне словаря)."""
    return [{"code": c, "text": H_RU.get(c)} for c in (codes or [])]


def crosscheck(our_codes, pub_codes):
    """Сверка наших пиктограмм (GHS0x) с пиктограммами PubChem. Возвращает совпадение/расхождения."""
    a, b = set(our_codes or []), set(pub_codes or [])
    return {
        "match": sorted(a & b),
        "only_ours": sorted(a - b),          # есть у нас, нет в PubChem (возможно лишнее)
        "only_pubchem": sorted(b - a),       # есть в PubChem, нет у нас (возможный пропуск)
        "agree": a == b,
    }
