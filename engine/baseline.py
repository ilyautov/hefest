_FIELDS = ("ppe", "first_aid", "storage")


def data_grade(sub: dict) -> str:
    present = sum(1 for f in _FIELDS if sub.get(f))
    if present == 3:
        return "passport"
    if present >= 1:
        return "partial"
    return "baseline"


def _merge(groups, key):
    """Собрать типовой текст по применимым группам (без дублей)."""
    parts, seen = [], set()
    for g in groups:
        t = GROUP_BASELINE.get(g, {}).get(key)
        if t and t not in seen:
            seen.add(t); parts.append(t)
    if not parts:
        return GENERIC[key]
    return " | ".join(parts)


def baseline_for(sub: dict) -> dict:
    """Типовое руководство по группе для вещества. Не заменяет паспорт."""
    groups = compat.classify(sub)
    hc = str(sub.get("hazard_class") or "")
    out = {
        "groups": [compat.GROUPS[g] for g in groups],
        "grade": data_grade(sub),
    }
    # Только недостающие поля заполняем типовым (паспортные не трогаем).
    for f in _FIELDS:
        if sub.get(f):
            out[f] = {"value": sub[f], "source": "паспорт"}
        else:
            out[f] = {"value": _merge(groups, f), "source": "типовое по группе"}
    # Усиление СИЗ для высоких классов опасности, если СИЗ типовые.
    if hc in ("1", "2") and out["ppe"]["source"] != "паспорт" and "противогаз" not in out["ppe"]["value"]:
        out["ppe"]["value"] += "; для высокого класса опасности — органы дыхания защищать обязательно (противогаз/респиратор по веществу)"
    out["disclaimer"] = ("Типовые меры по химической группе и классу опасности — НЕ из паспорта "
                         "конкретного вещества. Перед применением сверьте с официальным паспортом безопасности.")
    return out
