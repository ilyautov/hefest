# Быстрый индекс по «текущему токену» для подстановки актуальной ссылки.
def by_id(act_id):
    for a in REGISTER:
        if a["id"] == act_id:
            return a
    return None


def current_acts():
    """Только действующие акты — для раздела 15 паспорта."""
    return [a for a in REGISTER if a["status"] == "current"]


def applicable_for(out):
    """
    Какие действующие акты применимы к конкретному веществу (раздел 15 паспорта).
    out — собранный словарь из /substance. Возвращает список {id,title,governs,why}.
    """
    acts = []

    def add(act_id, why):
        a = by_id(act_id)
        if a and a["status"] == "current":
            acts.append({"id": a["id"], "title": a["title"], "governs": a["governs"], "why": why})

    add("ГОСТ 30333-2022", "общая структура паспорта безопасности")
    if out.get("hazard_class"):
        add("ГОСТ 12.1.007-76", "класс опасности вещества")
    if out.get("pdk_mgm3"):
        add("ГОСТ 12.1.005-88", "ПДК в воздухе рабочей зоны")
    if out.get("ghs") or out.get("pubchem"):
        add("ГОСТ 31340-2013", "предупредительная маркировка (СГС)")
    if out.get("pdk_mgm3") or out.get("sanpin") or out.get("sanpin_env"):
        add("СанПиН 1.2.3685-21", "гигиенические нормативы (ПДК)")
    if out.get("waste"):
        add("89-ФЗ", "обращение с отходами (раздел 13)")
        add("Приказ Минприроды № 536 (04.12.2014)", "класс опасности отхода (I–V)")
    return acts


def summary_counts():
    """Для дашборда соответствия: распределение актов по статусу."""
    by_status = {}
    for a in REGISTER:
        by_status[a["status"]] = by_status.get(a["status"], 0) + 1
    return {"total": len(REGISTER), "by_status": by_status}
