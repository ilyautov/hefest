def plant_tests(r, limit=3):
    """Плант-запросы из подключённого реестра: (запрос, множество допустимых веществ в top-1).

    Берутся площадки с наибольшим числом сопоставленных веществ — на них скоуп проверяется
    содержательно. Пустой реестр даёт пустой набор: плант-метрика просто не считается."""
    площадки = sorted(r.plants.values(),
                      key=lambda p: -len(p.get("matched_substances", [])))
    набор = {}
    for площадка in площадки[:limit]:
        вещества = set(площадка.get("matched_substances", []))
        if not вещества:
            continue
        набор[f"что опасного на площадке {площадка['plant']}"] = вещества
    return набор

def main():
    r = HybridRetriever()
    h1=h3=sec=plant_ok=plant_n=0; subj_n=0; lat=[]
    PLANT_SCOPE = plant_tests(r)
    print("="*78)
    for q, exp, kw in TESTS + [(q, None, None) for q in PLANT_SCOPE]:
        t=time.time(); res=r.query(q,k=3); lat.append((time.time()-t)*1000)
        top=res[0][0]
        if q in PLANT_SCOPE:
            plant_n+=1
            ok = top["substance"] in PLANT_SCOPE[q]
            plant_ok+=ok
            print(f"[{'OK ' if ok else 'MISS'}|PLANT] {q[:42]:42} -> {top['substance']}")
            continue
        subj_n+=1
        in3=any(c["substance"]==exp for c,_ in res); ok1=top["substance"]==exp
        h1+=ok1; h3+=in3
        seck = (kw is None) or (kw.lower() in top["section"].lower())
        if ok1 and seck: sec+=1
        flag="OK " if ok1 else ("~3 " if in3 else "MISS")
        print(f"[{flag}] {q[:46]:46} -> {top['substance']} / {top['section'][:24]}")
    print("="*78)
    print(f"Вещество top-1:          {h1}/{subj_n} = {h1/subj_n:.0%}")
    print(f"Вещество top-3:          {h3}/{subj_n} = {h3/subj_n:.0%}")
    print(f"Вещество+раздел top-1:   {sec}/{subj_n} = {sec/subj_n:.0%}")
    if plant_n:
        print(f"Плант-скоуп top-1:       {plant_ok}/{plant_n} = {plant_ok/plant_n:.0%}")
    else:
        print("Плант-скоуп top-1:       не считался — реестр площадок не подключён "
              "(см. DATA-LICENSE.md, раздел 4)")
    print(f"Latency: median {sorted(lat)[len(lat)//2]:.1f} ms, max {max(lat):.1f} ms (CPU, без GPU)")
    print(f"Корпус: {len(r.subs)} веществ, {len(r.chunks)} разделов-чанков, "
          f"площадок в реестре: {len(r.plants)}")

if __name__ == "__main__":
    main()
