    ("при какой температуре вспыхивает ацетон", "ацетон", "пожаротуш"),
    ("что делать если метанол попал внутрь, антидот", "метанол", "помощи"),
    ("какие перчатки нужны для ацетона", "ацетон", "Средства защиты"),
    ("как хранить серную кислоту, с чем несовместима", "серная кислота", "хранен"),
    ("ПДК формальдегида в воздухе рабочей зоны", "формальдегид", "Токсиколог"),
    ("едкий натр выделяет водород с какими металлами", "гидроксид натрия", "пожаротуш"),
    ("первая помощь при ожоге глаз щёлочью", "гидроксид натрия", "помощи"),
    ("какое вещество канцероген группа 1", "формальдегид", None),
    ("чем опасен аммиак при вдыхании", "аммиак", None),
    ("куда приливать кислоту в воду или воду в кислоту", "серная кислота", None),
    ("антидот при отравлении цианидом натрия", "цианид натрия", "помощи"),
    ("чем опасен фосген и когда наступает отёк лёгких", "фосген", None),
    ("этиленоксид взрывоопасность и канцерогенность", "окись этилена", None),
    ("как хранить винилхлорид", "винилхлорид", "хранен"),
    ("ПДК толуола рабочая зона", "толуол", "Токсиколог"),
    ("температура вспышки сероуглерода нет, ацетона да", "ацетон", None),
    ("чем опасен пентакарбонил железа", "пентакарбонил железа", None),
    ("первая помощь при вдыхании оксида углерода", "оксид углерода", "помощи"),
    ("несовместимость гипохлорита натрия с кислотами хлор", "гипохлорит натрия", None),
    ("перекись водорода хранение окислитель", "перекись водорода", "хранен"),
