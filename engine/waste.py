GENERIC = ("сбор в маркированную тару раздельно от несовместимых отходов; передача лицензированному "
           "оператору по обращению с отходами; несанкционированный сброс запрещён")

FRAMEWORK = [
    {"k": "Класс опасности отхода (I–V)",
     "v": "отдельная шкала от класса вещества (1–4); определяется по Приказу Минприроды № 536 "
          "от 04.12.2014 (критерии отнесения к I–V классам)"},
    {"k": "Код по ФККО",
     "v": "присваивает эколог предприятия — каталог организован по типу/происхождению отхода, не по CAS"},
    {"k": "Правовая база",
     "v": "89-ФЗ «Об отходах производства и потребления» от 24.06.1998"},
]


def for_substance(s):
    """Типовые меры удаления отходов по группе вещества + рамка норматива. Никаких кодов ФККО.
    Возвращает {measures:[...], groups:[...], framework:[...], source, needs_review, note} или базовое."""
    if not s:
        return None
    try:
        groups = compat.classify(s) or []
    except Exception:
        groups = []
    measures, seen = [], set()
    for g in groups:
        m = GROUP_WASTE.get(g)
        if m and m not in seen:
            seen.add(m)
            measures.append(m)
    if not measures:
        measures = [GENERIC]
    return {
        "measures": measures,
        "groups": [compat.GROUPS[g] for g in groups if g in compat.GROUPS],
        "framework": FRAMEWORK,
        "source": "типовое по группе",
        "needs_review": True,
        "note": "Меры — ТИПОВЫЕ по группе вещества, не из паспорта. Конкретный класс опасности отхода "
                "(I–V) и код ФККО определяет эколог предприятия по Приказу Минприроды № 536. Сверьте.",
    }
