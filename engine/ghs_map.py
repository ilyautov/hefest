# -*- coding: utf-8 -*-
"""
GHS-слой: 9 стандартных пиктограмм ООН (СГС) + сигнальное слово.

Выводится из НАШИХ данных: текстовых GHS-меток (поле ghs) + класса опасности
ГОСТ 12.1.007 (1..4). H-коды сами не присваиваем сверх тех, что уже есть в метках —
выдумывать классификацию в безопасность-критичном инструменте нельзя.

Пиктограммы (код, имя, что значит):
  GHS01 explosive   — взрывчатое
  GHS02 flammable   — пламя (горючее/ЛВЖ)
  GHS03 oxidizing   — окислитель
  GHS04 gas         — газ под давлением
  GHS05 corrosive   — коррозия (кожа/металл)
  GHS06 toxic       — острая токсичность (череп)
  GHS07 harmful     — раздражение/наркотич./сенсиб. кожи (восклицат. знак)
  GHS08 health      — канцероген/мутаген/репродукт./сенсиб. дых./аспирация
  GHS09 environment — опасность для водной среды
"""
import re

PICTOGRAMS = {
    "GHS01": "Взрывчатое",
    "GHS02": "Воспламеняющееся",
    "GHS03": "Окислитель",
    "GHS04": "Газ под давлением",
    "GHS05": "Коррозия / разъедание",
    "GHS06": "Острая токсичность",
    "GHS07": "Раздражитель / вредно",
    "GHS08": "Опасно для здоровья",
    "GHS09": "Опасно для среды",
}

# Правила: regex по тексту GHS-метки -> код пиктограммы.
_RULES = [
    (r"взрывчат|детонац|взрыв(?!оопасн)", "GHS01"),
    (r"воспламен|лвж|горюч|пожароопасн", "GHS02"),
    (r"окислит", "GHS03"),
    (r"газ под давлением|сжатый газ|сжиженн.{0,6}газ", "GHS04"),
    (r"коррози|разъеда|едк", "GHS05"),
    (r"острая токсичность\s*[123]\b|острая токсичность\s*1|смертельн|высокотоксич|сильнотоксич|токсичн.{0,12}вдыхан", "GHS06"),
    (r"острая токсичность\s*4|раздражени|наркотич|сенсибилизатор кожи|вредно", "GHS07"),
    (r"канцероген|мутаген|репродуктив|сенсибилизатор дыхат|аспирац|поражение органов|астма", "GHS08"),
    (r"водной среды|водн.{0,6}организм|эколог|окружающ.{0,6}сред", "GHS09"),
]

# Сигнальное слово «Опасно» (Danger). По СГС: острая токсичность кат.1-3,
# STOT SE 1 (H370), коррозия, канцероген, чрезвыч. воспламеняемость → Danger.
_DANGER = re.compile(r"острая токсичность\s*[123]\b|острая токсичность\s*[123]|смертельн|"
                     r"высокотоксич|поражение органов|поражение зрительн|h370|h331|"
                     r"коррози|канцероген|мутаген\s*1|чрезвыч.{0,6}воспламен|взрывчат")


def ghs_profile(sub: dict) -> dict:
    """Вернуть {pictograms:[{code,name}], signal, basis, confidence}."""
    labels = sub.get("ghs") or []
    text = " ".join(labels).lower()
    hc = sub.get("hazard_class")
    codes, basis = [], []

    for pat, code in _RULES:
        if re.search(pat, text) and code not in codes:
            codes.append(code)

    derived = False
    # Если меток нет/мало — консервативно дополняем по классу опасности ГОСТ 12.1.007.
    if not codes and hc in (1, 2, "1", "2"):
        codes.append("GHS06"); derived = True
        basis.append(f"класс опасности {hc} (ГОСТ 12.1.007) → острая токсичность")
    elif not codes and hc in (3, 4, "3", "4"):
        codes.append("GHS07"); derived = True
        basis.append(f"класс опасности {hc} (ГОСТ 12.1.007) → раздражитель/вредно")

    if labels:
        basis.append("GHS-метки паспорта: " + ", ".join(labels))

    signal = "Опасно" if (_DANGER.search(text) or str(hc) in ("1", "2")) else ("Осторожно" if codes else None)

    return {
        "pictograms": [{"code": c, "name": PICTOGRAMS[c]} for c in codes],
        "signal_word": signal,
        "hazard_class": hc,
        "basis": basis,
        "confidence": "derived" if (derived or not labels) else "from_labels",
        "note": "Знаки определены по данным паспорта и классу опасности (ГОСТ 12.1.007). "
                "Перед нанесением на тару сверьте с официальной классификацией опасности.",
    }
