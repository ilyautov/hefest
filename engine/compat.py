# -*- coding: utf-8 -*-
"""
Матрица совместимости хранения (сегрегация несовместимых веществ).

Обоснование: по данным U.S. Chemical Safety Board несовместимое хранение —
фактор в ~25% из 1200 химинцидентов 2000-2020. Источник истины для пары —
Раздел 10 SDS («Стабильность и реакционная способность») + Раздел 7 (хранение).

Логика:
  1) каждое вещество относим к одной/нескольким сегрегационным ГРУППАМ
     (кислоты, щёлочи, окислители, горючие, активные металлы, токсичные газы,
      цианиды, водо-реактивные, орг. растворители) — по hazard_class, GHS-меткам,
      тексту несовместимости (поле storage) и имени;
  2) канонические правила группа×группа дают вердикт (NO/CAUTION/OK) с причиной;
  3) причина дополняется ЦИТАТОЙ из Раздела 10 обоих веществ — без фабрикации.

Вердикты:
  forbidden  — нельзя хранить вместе (раздельные помещения/обвалование)
  caution    — допустимо при разнесении/вторичном контейнменте, нужен контроль
  ok         — известных несовместимостей между группами нет (НЕ гарантия —
               всегда сверять Раздел 10 паспорта)
"""
import re

# --- Сегрегационные группы (канонические классы хранения) ---
GROUPS = {
    "acid":        "Кислоты",
    "base":        "Щёлочи/основания",
    "oxidizer":    "Окислители",
    "flammable":   "Горючие/ЛВЖ",
    "react_metal": "Активные металлы",
    "tox_gas":     "Токсичные газы",
    "cyanide":     "Цианиды/сульфиды",
    "cl_release":  "Выделяют хлор с кислотой",
    "organic":     "Орг. растворители",
    "peroxide":    "Пероксиды/перекиси",
}

# Соли (не металлический натрий/калий и т.п.) — НЕ относим к активным металлам.
_SALT = re.compile(r"хлорид|сульфат|сульфид|нитрат|нитрит|цианид|гипохлорит|хлорат|"
                   r"карбонат|гидроксид|оксид|фосфат|ацетат|стеарат|силикат|алюминат|перманганат")
# Известные токсичные газы / сжиженные газы под давлением (классифицируем по имени-идентичности).
_TOX_GAS = re.compile(r"\bхлор\b|фосген|аммиак|сероводород|циановодород|синильн|"
                      r"диоксид серы|сернист|окись этилена|оксид этилена|винилхлорид|"
                      r"диборан|трифторид бора|хлороводород|фтороводород|"
                      r"цианистый водород|оксид углерода|угарн")

# Канонические правила сегрегации между группами.
# (g1, g2) -> (verdict, reason). Симметрично; самопары обрабатываются отдельно.
# Источники правил: NFPA, EPA/CSB segregation guidance, ГОСТ 12.1.004/совм. хранения.
_RULES = {
    ("acid", "base"):        ("forbidden", "Кислота + щёлочь: бурная экзотермическая нейтрализация, разогрев, разбрызгивание."),
    ("acid", "react_metal"): ("forbidden", "Кислота + активный металл: выделение водорода (H2), риск взрыва."),
    ("acid", "cyanide"):     ("forbidden", "Кислота + цианид/сульфид: выделение синильной кислоты (HCN) / сероводорода — смертельно."),
    ("acid", "oxidizer"):    ("caution",   "Кислоты с окислителями могут давать токсичные газы/тепло; разносить."),
    ("base", "react_metal"): ("forbidden", "Щёлочь + Al/Zn/Sn: выделение водорода (H2)."),
    ("base", "oxidizer"):    ("caution",   "Щёлочь + окислитель: возможен разогрев, разносить."),
    ("oxidizer", "flammable"): ("forbidden", "Окислитель + горючее/ЛВЖ: поддерживает/инициирует горение, риск пожара/взрыва."),
    ("oxidizer", "organic"):   ("forbidden", "Окислитель + органика: самовозгорание, экзотермическая реакция."),
    ("oxidizer", "react_metal"): ("caution", "Окислитель + металл: возможна интенсивная реакция; разносить."),
    ("oxidizer", "peroxide"):  ("forbidden", "Окислитель + пероксид: нестабильная система, риск детонации."),
    ("acid", "organic"):       ("caution",   "Концентрированные кислоты обезвоживают/окисляют органику — экзотермия; разносить."),
    ("cl_release", "acid"):    ("forbidden", "Гипохлорит/хлорат + кислота: выделение газообразного хлора (Cl2) — АХОВ."),
    ("cyanide", "acid"):       ("forbidden", "Цианид/сульфид + кислота: выделение HCN/H2S — смертельно (дублирует правило по кислоте)."),
    ("flammable", "tox_gas"):  ("caution",   "Горючее рядом с токсичным/окисляющим газом — разносить, контроль утечек."),
    ("tox_gas", "tox_gas"):    ("caution",   "Совместимость токсичных газов зависит от пары (напр. NH3+Cl2 — бурно); сверять Раздел 10."),
    ("base", "tox_gas"):       ("caution",   "Щелочной/кислотный газ в одной зоне с реактивными газами — разносить, сверять пару."),
}


def _rule(g1, g2):
    return _RULES.get((g1, g2)) or _RULES.get((g2, g1))


def classify(sub: dict) -> list:
    """Отнести вещество к сегрегационным группам ПО ЕГО ИДЕНТИЧНОСТИ
    (имя, класс опасности, собственные GHS-метки) — НЕ по тексту несовместимости.
    Текст «вдали от окислителей» описывает с чем нельзя, а не чем вещество является,
    поэтому storage/special для классификации НЕ используем (только для цитаты)."""
    name = (sub.get("name") or "").lower()
    ghs = " ".join(sub.get("ghs") or []).lower()  # собственные GHS-метки вещества
    g = set()

    # --- Кислоты / щёлочи (основания) — по имени ---
    if re.search(r"кислот", name) and not re.search(
            r"аминокислот|аскорбинов|фолиев|никотинов|желчны|жирны|нуклеинов|сумм|"
            r"соль|натри|кали|кальци|аммони|эфир|амид|ангидрид", name):
        g.add("acid")
    if re.search(r"гидроксид|едки[йяе]|щёлоч|щелоч", name) or re.search(r"аммиак|аммиач|анилин|\bамин|этаноламин|гидразин", name):
        g.add("base")

    # --- Окислители (по имени-аниону и собственной GHS-метке) ---
    if "окислит" in ghs or re.search(r"перекис|пероксид|надперекис|нитрат|нитрит|хлорат|перхлорат|"
                                     r"перманганат|хромат|бихромат|дихромат|пербор|персульфат|"
                                     r"гипохлорит|азотная кислота|хлорная кислота", name):
        g.add("oxidizer")
    if re.search(r"перекис|пероксид|надперекис", name):
        g.add("peroxide")
    # Выделяют хлор при контакте с кислотой (отдельный явный риск)
    if re.search(r"гипохлорит|хлорат|хлорит\b|хлорная известь", name):
        g.add("cl_release")

    # --- Горючие / ЛВЖ (собственная GHS-метка ИЛИ температура вспышки) ---
    if re.search(r"воспламен|лвж|горюч|легковоспламен", ghs):
        g.add("flammable")
    fp = sub.get("flash_point_c")
    try:
        if fp is not None and float(fp) <= 61:  # ЛВЖ по ГОСТ 12.1.044 (Tвсп ≤ 61°C)
            g.add("flammable")
    except (TypeError, ValueError):
        pass

    # --- Активные металлы: только сам металл, НЕ его соли ---
    if re.search(r"\b(натрий|калий|литий|магний|кальций|алюминий|цинк|рубидий|цезий)\b", name) \
            and not _SALT.search(name):
        g.add("react_metal")

    # --- Токсичные газы: по известному имени-идентичности ---
    if _TOX_GAS.search(name) or "газ под давлением" in ghs:
        g.add("tox_gas")

    # --- Цианиды / сульфиды (с кислотой -> HCN/H2S) ---
    if re.search(r"циан|сульфид|сероводород|синильн", name):
        g.add("cyanide")

    # --- Орг. растворители ---
    if re.search(r"толуол|ксилол|ацетон|метанол|этанол|изопропанол|бензол|"
                 r"эфир|гексан|гептан|уайт-спирит|растворител|углеводород", name):
        g.add("organic")

    return sorted(g)


def _quote_incompat(sub: dict) -> str:
    """Короткая цитата несовместимости из полей Раздела 10/7 (storage/special)."""
    for k in ("storage", "special"):
        t = (sub.get(k) or "").strip()
        if "несовмест" in t.lower() or "не допуск" in t.lower() or "вдали от" in t.lower():
            return t[:200]
    return (sub.get("storage") or "").strip()[:200]


def check(a: dict, b: dict) -> dict:
    """Проверить пару веществ. Возвращает вердикт + причины + цитаты Раздела 10."""
    ga, gb = classify(a), classify(b)
    worst = "ok"
    reasons = []
    rank = {"ok": 0, "caution": 1, "forbidden": 2}
    for g1 in ga:
        for g2 in gb:
            if g1 == g2:
                continue
            r = _rule(g1, g2)
            if r:
                v, why = r
                if rank[v] > rank[worst]:
                    worst = v
                reasons.append({"pair": [GROUPS[g1], GROUPS[g2]], "verdict": v, "why": why})
    # дедуп причин
    seen, uniq = set(), []
    for r in sorted(reasons, key=lambda x: -rank[x["verdict"]]):
        k = (tuple(sorted(r["pair"])), r["verdict"])
        if k not in seen:
            seen.add(k); uniq.append(r)
    return {
        "a": a.get("name"), "b": b.get("name"),
        "groups_a": [GROUPS[x] for x in ga], "groups_b": [GROUPS[x] for x in gb],
        "verdict": worst,
        "reasons": uniq[:5],
        "sds_a": _quote_incompat(a), "sds_b": _quote_incompat(b),
        "disclaimer": "Вывод сделан по группам совместимости и тексту раздела «Стабильность и реакционная "
                      "способность» паспортов. Перед размещением сверьте этот раздел каждого паспорта "
                      "и правила совместного хранения вашего объекта.",
        "confidence": "needs_review",
    }
